"""Brings into the Swift project what it shares with the web app, so that
there is one copy of each in the repository:

  icons/*.svg          ->  RSL/Generated/Icons.swift   (drawn from the same paths)
  fonts/GolosText.ttf  ->  RSL/Generated/
  model/labels.json    ->  RSL/Generated/
  server.json          ->  RSL/Generated/
  and the licences of the font and of ONNX Runtime

Run before XcodeGen:   python3 swift/tools/prepare.py
"""
import os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
OUT = os.path.join(HERE, "..", "RSL", "Generated")
os.makedirs(OUT, exist_ok=True)

# The two licence texts go into the app with what they cover.
for src in ("fonts/GolosText.ttf", "fonts/GOLOS-OFL.txt", "model/labels.json", "server.json",
            "vendor/LICENSE-onnxruntime.txt"):
    shutil.copy(os.path.join(ROOT, src), OUT)

def attr(tag, name, default=None):
    m = re.search(r'\b%s="([^"]*)"' % re.escape(name), tag)
    return m.group(1) if m else default

def swift_name(file):
    parts = file[:-4].split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])

icons = []
for f in sorted(os.listdir(os.path.join(ROOT, "icons"))):
    if not f.endswith(".svg"):
        continue
    s = open(os.path.join(ROOT, "icons", f), encoding="utf-8").read()
    box = [float(v) for v in re.search(r'<svg[^>]*viewBox="([^"]+)"', s).group(1).split()]
    s = re.sub(r"<defs>.*?</defs>", "", s, flags=re.S)       # a clip to the icon's own bounds
    parts = []
    for tag in re.findall(r"<path\b[^>]*>", s):
        d = attr(tag, "d")
        width = attr(tag, "stroke-width")
        if attr(tag, "stroke"):
            parts.append('.stroke("%s", %s)' % (d, width or "1"))
        else:
            parts.append('.fill("%s")' % d)
    icons.append("    static let %s = Icon(x: %g, y: %g, width: %g, height: %g, parts: [\n        %s,\n    ])"
                 % (swift_name(f), box[0], box[1], box[2], box[3], ",\n        ".join(parts)))

code = """// Generated by tools/prepare.py from icons/*.svg - do not edit by hand.
// The drawings are used exactly as designed; only the colour is set in code.

import CoreGraphics

enum Icons {
%s
}
""" % "\n\n".join(icons)
open(os.path.join(OUT, "Icons.swift"), "w", encoding="utf-8").write(code)
print(len(icons), "icons ->", os.path.relpath(os.path.join(OUT, "Icons.swift"), ROOT))
